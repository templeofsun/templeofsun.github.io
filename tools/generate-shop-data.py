#!/usr/bin/env python3
"""
Temple of Sun: the price list the cart reads.

Reads the 23 blends from tools/blend-pages.json (the same file the product
pages come from) and writes js/shop-data.js. Prices and names therefore live
in one place: change a price in blend-pages.json, run prepare-for-upload.py,
and the product page, the cart and the checkout all agree.

GENERATED FILE: do not edit js/shop-data.js by hand.

    python3 tools/generate-shop-data.py
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "tools" / "blend-pages.json"
OUT = ROOT / "js" / "shop-data.js"

COLLECTIONS = {
    "rainbow-collection.html": "The Rainbow Collection",
    "5-elements.html": "The 5 Elements",
}


def price_in_cents(text: str) -> int:
    number = re.sub(r"[^\d.,]", "", text).replace(",", ".")
    return round(float(number) * 100)


def bottle_size(text: str) -> str:
    """Only a real bottle size ("10ml"). The 5 Elements pages carry a chakra
    name in this field, which is not a size, so the cart shows none for them."""
    match = re.search(r"\d+(\.\d+)?\s*ml", text, re.I)
    return match.group(0).replace(" ", "") if match else ""


def main() -> None:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    products = {}
    for page, blends in data.items():
        for slug, blend in blends.items():
            products[slug] = {
                "name": blend["name"],
                "price": price_in_cents(blend["price"]),
                "size": bottle_size(blend["k"]),
                "collection": COLLECTIONS.get(page, ""),
                "url": f"products/{slug}.html",
                "image": f"assets/img/products/{slug}.webp",
            }

    body = json.dumps(products, ensure_ascii=False, indent=1)
    OUT.write_text(
        "/* Temple of Sun: price list for the cart.\n"
        "   GENERATED by tools/generate-shop-data.py from tools/blend-pages.json.\n"
        "   Do not edit by hand. Prices are in euro cents. */\n"
        f"window.TOS_PRODUCTS = {body};\n",
        encoding="utf-8",
    )
    no_size = [p["name"] for p in products.values() if not p["size"]]
    print(f"shop data: {len(products)} blends written to js/shop-data.js")
    if no_size:
        print(f"  no bottle size yet: {', '.join(no_size)}")


if __name__ == "__main__":
    main()
